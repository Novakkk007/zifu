const CN_NUM = ['零', '一', '二', '三', '四', '五', '六', '七', '八', '九']

/** 钱数 → 「三两九钱」式文本 */
export function qianToText(qian: number): string {
  const liang = Math.floor(qian / 10)
  const q = qian % 10
  if (q === 0) return `${CN_NUM[liang]}两`
  return `${CN_NUM[liang]}两${CN_NUM[q]}钱`
}

/** 查批语：越界或缺表返回 null */
export function lookupVerse(totalQian: number, gender: 'male' | 'female' = 'male'): string | null {
  if (!Number.isInteger(totalQian)) return null
  const table = gender === 'female' ? VERSES_FEMALE : VERSES_MALE
  return table[totalQian] ?? null
}

/** 查年重：jiaziIdx 越界返回 null */
export function lookupYearQian(jiaziIdx: number): number | null {
  if (!Number.isInteger(jiaziIdx) || jiaziIdx < 0 || jiaziIdx >= 60) return null
  return YEAR_QIAN[jiaziIdx]
}

/** 查月重：lunarMonth 取 1-12（闰月传入绝对值），越界返回 null */
export function lookupMonthQian(lunarMonth: number): number | null {
  if (!Number.isInteger(lunarMonth) || lunarMonth < 1 || lunarMonth > 12) return null
  return MONTH_QIAN[lunarMonth - 1]
}

/** 查日重：1-30，越界返回 null */
export function lookupDayQian(lunarDay: number): number | null {
  if (!Number.isInteger(lunarDay) || lunarDay < 1 || lunarDay > 30) return null
  return DAY_QIAN[lunarDay - 1]
}

/** 查时重：hourBranchIdx 0-11，越界返回 null */
export function lookupHourQian(hourBranchIdx: number): number | null {
  if (!Number.isInteger(hourBranchIdx) || hourBranchIdx < 0 || hourBranchIdx > 11) return null
  return HOUR_QIAN[hourBranchIdx]
}
