/**
 * 马星（驿马）按时支三合：申子辰马在寅、寅午戌马在申、
 * 巳酉丑马在亥、亥卯未马在巳。返回马星地支序（子=0）。
 */
export function maXingBranch(hourBranchIdx: number): number {
  if ([8, 0, 4].includes(hourBranchIdx)) return 2 // 申子辰→寅
  if ([2, 6, 10].includes(hourBranchIdx)) return 8 // 寅午戌→申
  if ([5, 9, 1].includes(hourBranchIdx)) return 11 // 巳酉丑→亥
  return 5 // 亥卯未→巳
}

