/** 常用术语组合导出 */
export const ALL_GLOSSARY: Record<string, GlossaryEntry> = {
  ...STEM_GLOSSARY,
  ...SHEN_GLOSSARY,
}

/** 按术语名查找 */
export function lookupGlossary(term: string): GlossaryEntry | undefined {
  return ALL_GLOSSARY[term]
}

/** 获取某术语关联的典籍列表（用于藏经阁互链） */
export function getRelatedBooks(term: string): string[] {
  const entry = ALL_GLOSSARY[term]
  if (!entry) return []
  const books = new Set<string>()
  if (entry.source) books.add(entry.source.book)
  // 递归查一级关联术语的出处
  for (const rel of entry.related.slice(0, 3)) {
    const relEntry = ALL_GLOSSARY[rel]
    if (relEntry?.source) books.add(relEntry.source.book)
  }
  return [...books]
}
